import {execFileSync} from 'node:child_process';
import {test,expect} from '@playwright/test';
const fixture=(mode:string)=>JSON.parse(execFileSync('php',['tests/browser/product-bulk-technical-fixture.php',mode],{encoding:'utf8'}));
test.use({actionTimeout: 15000});
let state:any;
test.beforeAll(()=>{state=fixture('setup')});
test.afterAll(()=>{fixture('cleanup')});
test('selected patch and filtered select all use the actual Filament selection',async({page})=>{
    test.setTimeout(240000);
    const errors:string[]=[];
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
    page.on('pageerror',e=>errors.push(e.message));
    page.on('requestfailed',r=>errors.push(r.url()));
    page.on('response',r=>{if(r.status()>=500||(r.url().includes('livewire')&&r.status()>=400))errors.push(String(r.status()))});
    await page.goto('/admin/login');
    await page.locator('[id="form.email"]').fill(state.email);
    await page.locator('[id="form.password"]').fill(state.password);
    await page.locator('button[type=submit]').click();
    await expect(page).toHaveURL(/\/admin\/?$/);
    await page.goto('/admin/products');
    const search=page.locator('.fi-ta-search-field input').first();
    await search.fill('BulkTechnicalSelected');
    await expect(page.locator('input.fi-ta-record-checkbox')).toHaveCount(3);
    for(const id of state.ids.slice(0,3))await page.locator('input.fi-ta-record-checkbox[value="'+id+'"]').check();
    await page.getByRole('button',{name:/Tác vụ hàng loạt|Bulk actions/i}).and(page.locator('[aria-haspopup=menu]')).click();
    await page.getByText('Cập nhật thông số kỹ thuật',{exact:true}).click();
    const modal=page.getByRole('dialog').filter({hasText:'Cập nhật thông số kỹ thuật'}).last();
    await modal.locator('select[id$=".technical_capacity_btu.operation"]').selectOption('set');
    await modal.locator('input[id$=".technical_capacity_btu.value"]').fill('11900');
    await modal.locator('select[id$=".capacity_kw.operation"]').selectOption('set');
    await modal.locator('input[id$=".capacity_kw.value"]').fill('3.5');
    await modal.locator('select[id$=".hp.operation"]').selectOption('set');
    await modal.locator('input[id$=".hp.value"]').fill('1.5');
    await modal.getByRole('button',{name:'Thêm thông số',exact:true}).click();
    await modal.locator('input[id*=".extras."][id$=".key"]').fill('Tính năng');
    await modal.locator('input[id*=".extras."][id$=".value"]').fill('Streamer');
    await modal.locator('textarea[id$=".reason"]').fill('Kiểm tra bulk trên SQLite');
    await modal.getByRole('button',{name:/Tiếp|Next/i}).click();
    await expect(modal.getByText('Bạn đang cập nhật 3 sản phẩm.')).toBeVisible();
    await modal.getByRole('checkbox').check();
    await modal.getByRole('button',{name:'Xác nhận cập nhật',exact:true}).click();
    await expect.poll(()=>fixture('snapshot').events.length).toBe(1);
    let snap=fixture('snapshot');
    for(const row of snap.rows.slice(0,3)){expect(row.technical_capacity_btu).toBe(11900);expect(row.capacity_kw).toBe('3.50');expect(row.hp).toBe('1.5')}
    expect(snap.rows[3].technical_capacity_btu).toBe(18000);
    expect(snap.events[0].action).toBe('BULK_TECHNICAL_UPDATE');
    expect(snap.events[0].operator_id).toBe(state.user_id);
    expect(snap.events[0].descriptor_json.operator_role).toBe('super_admin');
    expect(snap.events[0].batch_uuid).toBeTruthy();
    expect(snap.events[0].occurred_at).toBeTruthy();
    expect(snap.events.every((e:any)=>!['PENDING_APPROVAL','NEEDS_REVIEW','WAITING_REVIEW','APPROVE'].includes(e.action))).toBe(true);
    await page.goto('/san-pham?btu[]=9000-12000');
    for(const id of state.ids.slice(0,3))await expect(page.locator('#product-card-'+id)).toBeVisible();
    await page.locator('#product-card-'+state.ids[0]+' a').first().click();
    await page.getByRole('button',{name:'Thông số kỹ thuật',exact:true}).click();
    await expect(page.getByRole('row',{name:/Tính năng Streamer/i})).toBeVisible();
    await page.goto('/tim-kiem?q=11900');
    for(const id of state.ids.slice(0,3))await expect(page.locator('#product-card-'+id)).toBeVisible();
    await page.goto('/admin/products');
    await Promise.all([
        page.waitForResponse(r=>r.url().includes('livewire') && r.request().method()==='POST'),
        page.locator('.fi-ta-search-field input').first().fill('BulkTechnicalFiltered'),
    ]);
    await expect(page.getByText('BulkTechnicalFiltered 4',{exact:true})).toBeVisible();
    await expect(page.locator('input.fi-ta-record-checkbox')).toHaveCount(10);
    await page.locator('thead input[type=checkbox]').first().check();
    await expect(page.locator('input.fi-ta-record-checkbox').first()).toBeChecked();
    await page.getByText(/Chọn tất cả 27|Select all 27/i).click();
    await page.getByRole('button',{name:/Tác vụ hàng loạt|Bulk actions/i}).and(page.locator('[aria-haspopup=menu]')).click();
    await page.getByText('Cập nhật thông số kỹ thuật',{exact:true}).click();
    const allModal=page.getByRole('dialog').filter({hasText:'Cập nhật thông số kỹ thuật'}).last();
    await allModal.getByRole('tab', {name:'Điện', exact:true}).click();
    await allModal.locator('select[id$=".voltage.operation"]').selectOption('set');
    await allModal.locator('input[id$=".voltage.value"]').fill('230V');
    await allModal.locator('textarea[id$=".reason"]').fill('Filtered select all');
    await allModal.getByRole('button',{name:/Tiếp|Next/i}).click();
    await expect(allModal.getByText('Bạn đang cập nhật 27 sản phẩm.')).toBeVisible();
    await allModal.getByRole('checkbox').check();
    await allModal.getByRole('button',{name:'Xác nhận cập nhật',exact:true}).click();
    await expect.poll(()=>fixture('snapshot').events.length).toBe(2);
    snap=fixture('snapshot');
    expect(snap.events[1].product_ids_json).toHaveLength(27);
    for(const row of snap.rows.slice(3))expect(row.voltage).toBe('230V');
    for(const row of snap.rows.slice(0,3))expect(row.voltage).toBe('220V');
    await page.goto('/admin/products');
    const total=fixture('snapshot').total;
    await page.locator('thead input[type=checkbox]').first().check();
    await expect(page.locator('input.fi-ta-record-checkbox').first()).toBeChecked();
    await page.getByText(new RegExp('Chọn tất cả '+total+'|Select all '+total)).click();
    await page.getByRole('button',{name:/Tác vụ hàng loạt|Bulk actions/i}).and(page.locator('[aria-haspopup=menu]')).click();
    await page.getByText('Cập nhật thông số kỹ thuật',{exact:true}).click();
    const globalModal=page.getByRole('dialog').filter({hasText:'Cập nhật thông số kỹ thuật'}).last();
    await globalModal.getByRole('tab',{name:'Điện',exact:true}).click();
    await globalModal.locator('select[id$=".frequency.operation"]').selectOption('set');
    await globalModal.locator('input[id$=".frequency.value"]').fill('50Hz');
    await globalModal.locator('textarea[id$=".reason"]').fill('Chọn toàn bộ DB cô lập');
    await globalModal.getByRole('button',{name:/Tiếp|Next/i}).click();
    await expect(globalModal.getByText('Bạn đang cập nhật '+total+' sản phẩm.')).toBeVisible();
    await globalModal.getByRole('checkbox').check();
    await globalModal.getByRole('button',{name:'Xác nhận cập nhật',exact:true}).click();
    await expect.poll(()=>fixture('snapshot').events.length).toBe(3);
    expect(fixture('snapshot').events[2].product_ids_json).toHaveLength(total);
    expect(errors).toEqual([]);
});
